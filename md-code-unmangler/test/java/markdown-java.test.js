'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');
const { formatJavaMarkdown, looksLikeJava } = require('../../java/markdown-java.cjs');

const run = markdown => formatJavaMarkdown(markdown).text;

test('fences a flattened listing and undoes Markdown escapes', () => {
  assert.equal(run('Here it is:\n\nclass A { int month\\_days[]; void f() { x = y \\* 2; } }\n\nMore prose.'),
    'Here it is:\n\n```java\nclass A {\n  int month_days[];\n\n  void f() {\n    x = y * 2;\n  }\n}\n```\n\nMore prose.');
});

test("keeps Java's own escapes", () => {
  assert.equal(run('String dirname = "\\\\MyDir\\n";'), '```java\nString dirname = "\\\\MyDir\\n";\n```');
});

test('fences short snippets and listings continued from the previous page', () => {
  assert.equal(run('short s; short t;'), '```java\nshort s;\nshort t;\n```');
  assert.equal(run('depth + " by " + height + "."; } } class Demo { public static void main(String args[]) { f(); g(); } }'),
    '```java\n    depth + " by " + height + ".";\n  }\n}\n\nclass Demo {\n  public static void main(String args[]) {\n    f();\n    g();\n  }\n}\n```');
});

test('leaves prose, syntax templates, program output and C alone', () => {
  for (const text of [
    'For example, this call: fmt.format("%X", 250); creates this string: FA',
    'for(*initialization*; *condition*; *iteration*) { // body }',
    'In 1000 days light will travel about 16070400000000 miles.',
    'The **public** keyword is an *access modifier*.',
    '/* DO NOT EDIT THIS FILE */ #include <jni.h> #ifndef _Included_NativeDemo',
  ]) assert.equal(run(text), text);
});

test('leaves existing fences untouched and keeps CRLF line endings', () => {
  const fenced = '```java\nint x;\n```';
  assert.equal(run(fenced), fenced);
  assert.equal(run('Intro.\r\n\r\nint x;\r\n'), 'Intro.\r\n\r\n```java\r\nint x;\r\n```\r\n');
});

test('recognizes how listings start', () => {
  for (const code of ['// A comment.', 'import java.io.*;', 'Gen(T o) { ob = o; }', 'T getob() { return ob; }',
    'try(FileInputStream fin = new FileInputStream(f)) {', '@interface SomeAnno { int value(); }', 'class getCharsDemo { }',
    'return sum / nums.length; }']) assert.equal(looksLikeJava(code), true, code);
});
